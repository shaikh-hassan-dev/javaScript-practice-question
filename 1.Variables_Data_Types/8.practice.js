// Values can transform from one type to another. The Codex teaches: 'Number() converts to numbers, String() converts to strings...'

// Create a variable `strNumber` with the string value '42'. Then create a variable `actualNumber` that converts it to a real number using Number(). Log actualNumber to the console.

// Convert string to number
const strNumber = '42';
// Convert strNumber to a real number
const actualNumber = Number(strNumber);
console.log(actualNumber);
